def analysis_result_help_entries(method: str) -> list[tuple[str, str]]:
    """Возвращает пояснения к результатам конкретного метода анализа."""

    return ANALYSIS_RESULT_HELP.get(method, [])


def render_analysis_result_help(method: str) -> None:
    """Отображает короткий блок пояснений к результатам метода."""

    entries = analysis_result_help_entries(method)
    if not entries:
        return

    with st.expander(f"Как читать результат: {ANALYSIS_METHOD_LABELS.get(method, method)}", expanded=False):
        columns = st.columns(2)
        for index, (title, text) in enumerate(entries):
            with columns[index % 2]:
                st.markdown(f"**{title}**")
                st.caption(text)
